 const city=/^(.+) · crime (\d+)$/.exec(text);
 if(city)return kingdomLabel(city[1])+' · الجريمة '+city[2];
 const sentence=kingdomLegacySentence(text);
 if(sentence!==text)return sentence;
 const size=/^(\d+) named city$/i.exec(text);
 if(size)return size[1]+' مدينة مسمّاة';
 if(!/^[+−\-\d.]/.test(text))return text;
 return text.replace(/ of GDP|\s+GDP/g,' من الناتج المحلي')
  .replace(/% defense/g,'٪ من الدفاع').replace(/ per year/g,' سنوياً')
  .replace(/\bvs\b/g,'مقابل').replace(/\bfloor\b/g,'حد أدنى')
  .replace(/\breal\b/g,'حقيقي').replace(/\bpts\b/g,'نقطة')
  .replace(/\bthousand\b/g,'ألف').replace(/\bindex\b/g,'مؤشر')
  .replace(/\bpeople\b/g,'نسمة').replace(/(?<=\d)m\s+نسمة$/, ' مليون نسمة')
  .replace(/Near potential/g,'قريب من الناتج المحتمل').replace(/Moderate pressure/g,'ضغط متوسط')
