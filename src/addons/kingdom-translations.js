function localizeKingdomFragment(root){
 if(root.nodeType===3){
  const original=root.data.trim();
  const translated=kingdomDisplayText(original);
  if(translated!==original)root.data=root.data.replace(original,translated);
  return;
 }
 if(root.nodeType!==1)return;
 if(root.tagName==='OPTION'&&/^[A-Z]{3}$/.test(root.value)){
  const n=nation(root.value);
  if(n&&root.textContent.trim()===n.name){
   const localized=kingdomNationName(n);
   if(localized!==n.name)root.textContent=localized;
  }
 }
 for(const key of ['title','aria-label','placeholder']){
  const value=root.getAttribute(key);
  if(value){
   const translated=kingdomLabel(value);
   if(translated!==value)root.setAttribute(key,translated);
  }
 }
 if(!['SCRIPT','STYLE','TEXTAREA','INPUT'].includes(root.tagName)){
  for(const child of root.childNodes)localizeKingdomFragment(child);
 }
}

function watchKingdomTranslations(){
 if(typeof MutationObserver!=='function'||!document.body)return;
 const scope='#panel,#countryhead,#events,#modalContent,#legend,#toast';
 const roots=[...document.querySelectorAll(scope)];
 const observer=new MutationObserver(records=>{
  if(!S?.kingdom)return;
  for(const record of records){
   if(record.type==='childList'){
    for(const child of record.addedNodes)localizeKingdomFragment(child);
   }else localizeKingdomFragment(record.target);
  }
 });
 for(const root of roots)observer.observe(root,{
  subtree:true,childList:true,characterData:true,attributes:true,
  attributeFilter:['title','aria-label','placeholder']
 });
}

